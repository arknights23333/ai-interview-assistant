-- 用户账号及基础资料。注册角色由服务端赋值，不接受客户端指定。
CREATE TABLE app_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  username VARCHAR(64) NOT NULL,
  email VARCHAR(254) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  nickname VARCHAR(64) NOT NULL,
  avatar VARCHAR(1024),
  role VARCHAR(16) NOT NULL DEFAULT 'USER',
  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_app_user PRIMARY KEY (id),
  CONSTRAINT uk_app_user_username UNIQUE (username),
  CONSTRAINT ck_app_user_username_not_blank CHECK (BTRIM(username) <> ''),
  CONSTRAINT ck_app_user_email_not_blank CHECK (BTRIM(email) <> ''),
  CONSTRAINT ck_app_user_password_hash_not_blank CHECK (BTRIM(password_hash) <> ''),
  CONSTRAINT ck_app_user_nickname_not_blank CHECK (BTRIM(nickname) <> ''),
  CONSTRAINT ck_app_user_role CHECK (role IN ('USER', 'ADMIN')),
  CONSTRAINT ck_app_user_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

-- 邮箱唯一性不区分大小写，避免同一邮箱因大小写不同重复注册。
CREATE UNIQUE INDEX uk_app_user_email ON app_user (LOWER(email));

COMMENT ON TABLE app_user IS '用户账号及基础资料';
COMMENT ON COLUMN app_user.id IS '用户主键，数据库自增生成';
COMMENT ON COLUMN app_user.username IS '登录账号，唯一，区分大小写';
COMMENT ON COLUMN app_user.email IS '已验证邮箱，唯一性不区分大小写';
COMMENT ON COLUMN app_user.password_hash IS '密码哈希，使用 BCrypt，不存储明文密码';
COMMENT ON COLUMN app_user.nickname IS '昵称，允许重复';
COMMENT ON COLUMN app_user.avatar IS '头像的稳定文件标识或地址，未设置时为空';
COMMENT ON COLUMN app_user.role IS '角色：USER 普通用户，ADMIN 管理员';
COMMENT ON COLUMN app_user.status IS '账号状态：ACTIVE 正常，DISABLED 禁用';
COMMENT ON COLUMN app_user.created_at IS '创建时间';
COMMENT ON COLUMN app_user.updated_at IS '更新时间，插入时提供默认值，后续由应用维护';
