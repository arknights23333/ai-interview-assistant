-- 一份简历可以有多次分析；状态属于本次分析，报告在成功后写入。
CREATE TABLE resume_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    resume_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    provider VARCHAR(64) NOT NULL,
    model_name VARCHAR(128) NOT NULL,
    prompt_version VARCHAR(64) NOT NULL,
    overall_score INTEGER,
    score_detail JSONB,
    summary TEXT,
    strengths JSONB,
    suggestions JSONB,
    error_message VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,

    CONSTRAINT pk_resume_analysis PRIMARY KEY (id),
    CONSTRAINT fk_resume_analysis_resume
        FOREIGN KEY (resume_id) REFERENCES resume(id) ON DELETE CASCADE,
    CONSTRAINT ck_resume_analysis_status
        CHECK (status IN ('PENDING', 'PROCESSING', 'SUCCESS', 'FAILED')),
    CONSTRAINT ck_resume_analysis_provider_not_blank CHECK (BTRIM(provider) <> ''),
    CONSTRAINT ck_resume_analysis_model_name_not_blank CHECK (BTRIM(model_name) <> ''),
    CONSTRAINT ck_resume_analysis_prompt_version_not_blank CHECK (BTRIM(prompt_version) <> ''),
    CONSTRAINT ck_resume_analysis_overall_score CHECK (overall_score BETWEEN 0 AND 100),
    CONSTRAINT ck_resume_analysis_score_detail_object
        CHECK (score_detail IS NULL OR jsonb_typeof(score_detail) = 'object'),
    CONSTRAINT ck_resume_analysis_strengths_array
        CHECK (strengths IS NULL OR jsonb_typeof(strengths) = 'array'),
    CONSTRAINT ck_resume_analysis_suggestions_array
        CHECK (suggestions IS NULL OR jsonb_typeof(suggestions) = 'array'),
    CONSTRAINT ck_resume_analysis_completed_at
        CHECK (completed_at IS NULL OR completed_at >= created_at)
);

-- 分析历史和最新报告按简历查询；相同创建时间以 ID 稳定排序。
CREATE INDEX idx_resume_analysis_resume_created
    ON resume_analysis (resume_id, created_at DESC, id DESC);

COMMENT ON TABLE resume_analysis IS '简历分析记录及报告，一份简历可有多次分析';
COMMENT ON COLUMN resume_analysis.id IS '数据库自增主键';
COMMENT ON COLUMN resume_analysis.resume_id IS '所属简历ID，访问权限及回收站状态以关联简历为准';
COMMENT ON COLUMN resume_analysis.status IS '本次分析状态：PENDING等待、PROCESSING处理中、SUCCESS成功、FAILED失败';
COMMENT ON COLUMN resume_analysis.provider IS '本次分析使用的模型供应商标识，不随平台默认配置变化';
COMMENT ON COLUMN resume_analysis.model_name IS '本次分析实际调用的模型名称，不保存API Key';
COMMENT ON COLUMN resume_analysis.prompt_version IS '本次分析使用的提示词版本';
COMMENT ON COLUMN resume_analysis.overall_score IS '总分，范围0至100，分析尚未成功时可为空';
COMMENT ON COLUMN resume_analysis.score_detail IS '评分明细JSON对象，包含各评分维度及分数';
COMMENT ON COLUMN resume_analysis.summary IS '简历分析概况';
COMMENT ON COLUMN resume_analysis.strengths IS '优点列表，JSON数组';
COMMENT ON COLUMN resume_analysis.suggestions IS '修改建议列表，JSON数组';
COMMENT ON COLUMN resume_analysis.error_message IS '本次分析失败原因';
COMMENT ON COLUMN resume_analysis.created_at IS '本次分析记录创建时间';
COMMENT ON COLUMN resume_analysis.completed_at IS '本次分析结束时间，成功或失败时填写，未结束时为空';
