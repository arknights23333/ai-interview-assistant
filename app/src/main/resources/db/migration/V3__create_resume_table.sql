-- 简历记录：AI 分析状态及报告由后续的分析记录表保存。
CREATE TABLE resume (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    create_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    file_hash VARCHAR(64) NOT NULL,
    file_size BIGINT NOT NULL,
    file_name VARCHAR(256) NOT NULL,
    resume_content TEXT,
    storage_key VARCHAR(512) NOT NULL,
    content_type VARCHAR(128) NOT NULL,
    parse_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    parse_error VARCHAR(500),
    delete_time TIMESTAMPTZ,

    CONSTRAINT pk_resume PRIMARY KEY (id),
    CONSTRAINT fk_resume_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT ck_resume_file_size CHECK (file_size > 0),
    CONSTRAINT ck_resume_file_hash CHECK (file_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_resume_file_name_not_blank CHECK (BTRIM(file_name) <> ''),
    CONSTRAINT ck_resume_storage_key_not_blank CHECK (BTRIM(storage_key) <> ''),
    CONSTRAINT ck_resume_content_type_not_blank CHECK (BTRIM(content_type) <> ''),
    CONSTRAINT ck_resume_parse_status
        CHECK (parse_status IN ('PENDING', 'PROCESSING', 'SUCCESS', 'FAILED'))
);

-- 同一用户的有效简历按文件内容去重；回收站记录不阻止再次上传。
CREATE UNIQUE INDEX uk_resume_user_file_hash_active
    ON resume (user_id, file_hash)
    WHERE delete_time IS NULL;

-- 当前用户的有效简历按上传时间倒序展示，ID 用于同时间记录的稳定排序。
CREATE INDEX idx_resume_user_create_active
    ON resume (user_id, create_at DESC, id DESC)
    WHERE delete_time IS NULL;

COMMENT ON TABLE resume IS '用户简历表';
COMMENT ON COLUMN resume.id IS '数据库自增主键';
COMMENT ON COLUMN resume.user_id IS '所属用户ID';
COMMENT ON COLUMN resume.create_at IS '创建时间，即首次上传时间';
COMMENT ON COLUMN resume.file_hash IS '文件内容的SHA-256哈希，小写十六进制，共64个字符';
COMMENT ON COLUMN resume.file_size IS '文件大小，单位为字节';
COMMENT ON COLUMN resume.file_name IS '上传时的原始文件名';
COMMENT ON COLUMN resume.resume_content IS '解析出的简历正文，尚未解析成功时可以为空';
COMMENT ON COLUMN resume.storage_key IS '原始文件在对象存储桶内的对象标识，不是访问URL';
COMMENT ON COLUMN resume.content_type IS '服务端检测出的文件MIME类型';
COMMENT ON COLUMN resume.parse_status IS '解析状态：PENDING等待、PROCESSING处理中、SUCCESS成功、FAILED失败';
COMMENT ON COLUMN resume.parse_error IS '解析失败原因，成功时清空';
COMMENT ON COLUMN resume.delete_time IS '移入回收站的时间；为空表示有效，恢复时设回NULL';
