CREATE TABLE knowledge_base(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    create_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_knowledge_base PRIMARY KEY (id),
    CONSTRAINT fk_knowledge_base_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT ck_knowledge_base_name_not_empty CHECK (BTRIM(name) <> ''),
    CONSTRAINT ck_knowledge_base_time_order CHECK (create_at <= update_at)
);

CREATE TABLE document(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    knowledge_base_id BIGINT NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    file_hash VARCHAR(64) NOT NULL,
    storage_key VARCHAR(255) NOT NULL,
    file_size  BIGINT NOT NULL,
    content_type VARCHAR(128) NOT NULL,
    process_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    process_error VARCHAR(500),
    create_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_document PRIMARY KEY (id),
    CONSTRAINT fk_knowledge_base_document_key FOREIGN KEY (knowledge_base_id) REFERENCES knowledge_base(id) ON DELETE RESTRICT,
    CONSTRAINT ck_document_file_hash CHECK (file_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_document_original_filename_not_blank CHECK (BTRIM(original_filename) <> ''),
    CONSTRAINT ck_document_storage_key_not_blank CHECK (BTRIM(storage_key) <> ''),
    CONSTRAINT ck_document_content_type_not_blank CHECK (BTRIM(content_type) <> ''),
    CONSTRAINT ck_document_status_check CHECK(process_status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_document_file_size CHECK (file_size > 0),
    CONSTRAINT ck_document_time_order CHECK (create_at <= update_at)
);
CREATE UNIQUE INDEX idx_knowledge_base_document ON document (knowledge_base_id, file_hash);

COMMENT ON TABLE knowledge_base IS '用户创建的私有知识库，一个知识库可包含多份文档';
COMMENT ON COLUMN knowledge_base.id IS '知识库主键，由数据库自增生成';
COMMENT ON COLUMN knowledge_base.user_id IS '所属用户 ID，关联 app_user.id';
COMMENT ON COLUMN knowledge_base.name IS '知识库名称';
COMMENT ON COLUMN knowledge_base.create_at IS '知识库创建时间';
COMMENT ON COLUMN knowledge_base.update_at IS '知识库最近一次修改时间，由应用维护';

COMMENT ON TABLE document IS '知识库中的原始文件及其处理状态';
COMMENT ON COLUMN document.id IS '文档主键，由数据库自增生成';
COMMENT ON COLUMN document.knowledge_base_id IS '所属知识库 ID，关联 knowledge_base.id';
COMMENT ON COLUMN document.original_filename IS '上传时的原始文件名';
COMMENT ON COLUMN document.file_hash IS '文件的 SHA-256 小写十六进制哈希，用于同库内去重';
COMMENT ON COLUMN document.storage_key IS '原始文件在对象存储中的对象键';
COMMENT ON COLUMN document.file_size IS '原始文件大小，单位为字节';
COMMENT ON COLUMN document.content_type IS '原始文件的 MIME 类型';
COMMENT ON COLUMN document.process_status IS '处理状态：PENDING 待处理、PROCESSING 处理中、COMPLETED 已完成、FAILED 失败';
COMMENT ON COLUMN document.process_error IS '文档处理失败原因，可为空';
COMMENT ON COLUMN document.create_at IS '文档记录创建时间';
COMMENT ON COLUMN document.update_at IS '文档记录最近一次修改时间，由应用维护';
