CREATE TABLE interview_schedule(
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        user_id BIGINT NOT NULL,
        create_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        update_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        company_name VARCHAR(255) NOT NULL,
        position_name VARCHAR(255) NOT NULL,
        start_at TIMESTAMPTZ NOT NULL,
        end_at TIMESTAMPTZ ,
        interview_type VARCHAR(16) NOT NULL,
        meeting_url TEXT ,
        location VARCHAR(255) ,
        round_number INTEGER ,
        status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
        notes TEXT,

        CONSTRAINT pk_interview_schedule PRIMARY KEY (id),
        CONSTRAINT fk_interview_schedule_user FOREIGN KEY (user_id) REFERENCES app_user(id),
        CONSTRAINT ck_interview_schedule_status CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED')),
        CONSTRAINT ck_interview_schedule_end_after_start CHECK (end_at IS NULL OR end_at > start_at),
        CONSTRAINT ck_interview_schedule_round_number_positive CHECK(round_number IS NULL OR round_number >0)
);
CREATE INDEX idx_interview_schedule_user_start ON interview_schedule (user_id,start_at,id);

COMMENT ON TABLE interview_schedule IS '用户面试日程，每条记录对应一场真实面试';
COMMENT ON COLUMN interview_schedule.id IS '面试日程主键，由数据库自增生成';
COMMENT ON COLUMN interview_schedule.user_id IS '所属用户ID，关联app_user.id';
COMMENT ON COLUMN interview_schedule.create_at IS '日程记录创建时间';
COMMENT ON COLUMN interview_schedule.update_at IS '日程记录最近一次修改时间，插入时提供默认值，后续由应用维护';
COMMENT ON COLUMN interview_schedule.company_name IS '面试公司名称';
COMMENT ON COLUMN interview_schedule.position_name IS '应聘岗位名称';
COMMENT ON COLUMN interview_schedule.start_at IS '面试开始时间';
COMMENT ON COLUMN interview_schedule.end_at IS '预计结束时间，可为空，填写时须晚于开始时间';
COMMENT ON COLUMN interview_schedule.interview_type IS '面试方式，例如线上、线下或电话';
COMMENT ON COLUMN interview_schedule.meeting_url IS '线上面试会议链接，可为空';
COMMENT ON COLUMN interview_schedule.location IS '线下面试地点，可为空';
COMMENT ON COLUMN interview_schedule.round_number IS '面试轮次，可为空，填写时须为正整数';
COMMENT ON COLUMN interview_schedule.status IS '日程状态，PENDING待进行、COMPLETED已完成、CANCELLED已取消';
COMMENT ON COLUMN interview_schedule.notes IS '面试备注，可记录联系人或准备事项';
