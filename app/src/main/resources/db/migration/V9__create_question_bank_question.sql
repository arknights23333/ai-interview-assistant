-- 复合外键需要对应的唯一键，以保证题目只能引用所属知识库中的文档。
ALTER TABLE document
    ADD CONSTRAINT uk_document_knowledge_base_id_id UNIQUE (knowledge_base_id, id);

-- 一行代表原题或其修改草稿，启用版在草稿采纳前继续供面试抽取。
CREATE TABLE question_bank_question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 采纳修改时保留原题 ID
    knowledge_base_id BIGINT NOT NULL, -- 通过知识库判断用户归属
    source_document_id BIGINT, -- 每题最多一份来源文档，手动录题可省略
    original_question_id BIGINT, -- 仅修改草稿指向原题，新题草稿为空
    creation_type VARCHAR(16) NOT NULL, -- 最初创建方式，AI 重写不改变原值
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT', -- DRAFT 草稿、ACTIVE 启用、ARCHIVED 归档
    question TEXT NOT NULL, -- 草稿至少填写题干
    job_direction VARCHAR(64), -- 启用前补齐，与面试会话的岗位方向对应
    difficulty VARCHAR(16), -- 启用前补齐，与面试会话的难度对应
    category VARCHAR(64), -- 可选的考察分类
    reference_answer TEXT, -- 草稿可暂缺参考答案
    key_points_json JSONB NOT NULL DEFAULT '[]', -- 启用时至少有一个有效评分要点
    scoring_rubric TEXT, -- 可选的评分标准
    follow_up_candidates_json JSONB NOT NULL DEFAULT '[]', -- 可选的现场追问素材
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_question_bank_question PRIMARY KEY (id),
    CONSTRAINT uk_question_bank_question_base_id UNIQUE (knowledge_base_id, id),
    CONSTRAINT fk_question_bank_question_base FOREIGN KEY (knowledge_base_id)
        REFERENCES knowledge_base(id) ON DELETE CASCADE,
    CONSTRAINT fk_question_bank_question_document FOREIGN KEY (knowledge_base_id, source_document_id)
        REFERENCES document(knowledge_base_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_question_bank_question_original FOREIGN KEY (knowledge_base_id, original_question_id)
        REFERENCES question_bank_question(knowledge_base_id, id) ON DELETE CASCADE,
    CONSTRAINT ck_question_bank_question_creation_type CHECK (creation_type IN ('MANUAL', 'AI_GENERATED')),
    CONSTRAINT ck_question_bank_question_ai_source CHECK (creation_type <> 'AI_GENERATED' OR source_document_id IS NOT NULL),
    CONSTRAINT ck_question_bank_question_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    CONSTRAINT ck_question_bank_question_original CHECK (
        original_question_id IS NULL OR (status = 'DRAFT' AND original_question_id <> id)
    ),
    CONSTRAINT ck_question_bank_question_text CHECK (question ~ '[^[:space:]]'),
    CONSTRAINT ck_question_bank_question_key_points CHECK (
        jsonb_typeof(key_points_json) = 'array'
        AND NOT jsonb_path_exists(key_points_json, 'strict $[*] ? (@.type() != "string")')
    ),
    CONSTRAINT ck_question_bank_question_follow_ups CHECK (jsonb_typeof(follow_up_candidates_json) = 'array'),
    CONSTRAINT ck_question_bank_question_active_fields CHECK (
        status <> 'ACTIVE' OR (
            job_direction IS NOT NULL AND job_direction ~ '[^[:space:]]'
            AND difficulty IS NOT NULL AND difficulty ~ '[^[:space:]]'
            AND reference_answer IS NOT NULL AND reference_answer ~ '[^[:space:]]'
            AND jsonb_path_exists(key_points_json, 'strict $[*] ? (@ like_regex "[^[:space:]]")')
        )
    ),
    CONSTRAINT ck_question_bank_question_time_order CHECK (created_at <= updated_at)
);

-- 一道原题最多保留一份修改草稿。题干允许相同，例如只修改参考答案时。
CREATE UNIQUE INDEX uk_question_bank_question_revision
    ON question_bank_question (original_question_id) WHERE original_question_id IS NOT NULL;
CREATE INDEX idx_question_bank_question_document
    ON question_bank_question (source_document_id) WHERE source_document_id IS NOT NULL;
CREATE INDEX idx_question_bank_question_selection
    ON question_bank_question (knowledge_base_id, status, job_direction, difficulty);

COMMENT ON TABLE question_bank_question IS '知识库题库原题与修改草稿，创建面试后由本场题目表保存快照';
COMMENT ON COLUMN question_bank_question.id IS '题库记录主键，采纳草稿时原题 ID 保持不变';
COMMENT ON COLUMN question_bank_question.knowledge_base_id IS '所属知识库 ID，删除知识库时一并删除';
COMMENT ON COLUMN question_bank_question.source_document_id IS '同库来源文档 ID，删除来源文档时一并删除，手动录题可为空';
COMMENT ON COLUMN question_bank_question.original_question_id IS '修改草稿所对应的原题 ID，新题草稿、启用题和归档题为空';
COMMENT ON COLUMN question_bank_question.creation_type IS '原题最初来自手动录入 MANUAL 或 AI 生成 AI_GENERATED';
COMMENT ON COLUMN question_bank_question.status IS '题目状态：DRAFT 草稿、ACTIVE 启用、ARCHIVED 归档';
COMMENT ON COLUMN question_bank_question.question IS '题干，保存草稿时必填';
COMMENT ON COLUMN question_bank_question.job_direction IS '专项面试的岗位方向，启用时必填';
COMMENT ON COLUMN question_bank_question.difficulty IS '专项面试的难度，启用时必填';
COMMENT ON COLUMN question_bank_question.category IS '考察分类，可为空';
COMMENT ON COLUMN question_bank_question.reference_answer IS '参考答案，启用时必填';
COMMENT ON COLUMN question_bank_question.key_points_json IS '评分要点字符串数组，启用时至少有一个非空白要点';
COMMENT ON COLUMN question_bank_question.scoring_rubric IS '可选的单题评分标准';
COMMENT ON COLUMN question_bank_question.follow_up_candidates_json IS '可选的候选追问数组，供现场追问参考';
COMMENT ON COLUMN question_bank_question.created_at IS '本条记录创建时间';
COMMENT ON COLUMN question_bank_question.updated_at IS '本条记录最近修改时间，由应用维护';
