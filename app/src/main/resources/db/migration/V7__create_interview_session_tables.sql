-- 用户的一场文字面试，普通面试和知识库专项共用
CREATE TABLE interview_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 面试会话主键，由数据库自增生成，也是接口使用的会话 ID
    user_id BIGINT NOT NULL, -- 所属用户 ID，关联 app_user.id
    source_type VARCHAR(32) NOT NULL, -- 题目来源：NORMAL 普通文字面试，KNOWLEDGE_BASE 知识库专项
    resume_id BIGINT, -- 关联的简历 ID，可为空；删除简历后解除关联，保留本场问答
    knowledge_base_id BIGINT, -- 专项面试来源知识库 ID；删库后置空，题目快照和面试进度继续保留
    job_direction VARCHAR(64) NOT NULL, -- 本场面试的岗位方向；专项面试填写所选题库方向
    job_description TEXT, -- 用户提供的岗位描述，可为空
    difficulty VARCHAR(16) NOT NULL, -- 本场面试的难度标识
    main_question_count INTEGER NOT NULL, -- 计划主问题数量，不包含追问
    current_question_id BIGINT, -- 本场当前题目 ID，尚未指定或面试结束后可为空
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS', -- 会话状态：IN_PROGRESS 进行中，可离开后继续；COMPLETED 已交卷或已结束
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 面试会话创建时间
    completed_at TIMESTAMPTZ, -- 面试结束时间，进行中为空

    CONSTRAINT pk_interview_session PRIMARY KEY (id),
    CONSTRAINT fk_interview_session_user
        FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_interview_session_resume
        FOREIGN KEY (resume_id) REFERENCES resume(id) ON DELETE SET NULL,
    CONSTRAINT fk_interview_session_knowledge_base
        FOREIGN KEY (knowledge_base_id) REFERENCES knowledge_base(id) ON DELETE SET NULL,
    CONSTRAINT ck_interview_session_source_type CHECK (source_type IN ('NORMAL', 'KNOWLEDGE_BASE')),
    CONSTRAINT ck_interview_session_source_knowledge_base
        CHECK (source_type = 'KNOWLEDGE_BASE' OR knowledge_base_id IS NULL),
    CONSTRAINT ck_interview_session_job_direction_not_blank CHECK (BTRIM(job_direction) <> ''),
    CONSTRAINT ck_interview_session_difficulty_not_blank CHECK (BTRIM(difficulty) <> ''),
    CONSTRAINT ck_interview_session_main_question_count CHECK (main_question_count > 0),
    CONSTRAINT ck_interview_session_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT ck_interview_session_completed_at CHECK (
        (status = 'IN_PROGRESS' AND completed_at IS NULL)
        OR (status = 'COMPLETED' AND completed_at IS NOT NULL AND completed_at >= created_at)
    )
);

-- 本场面试的题目快照与作答，每道主问题和实际提出的追问各占一行
CREATE TABLE interview_session_question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY, -- 本场题目主键，由数据库自增生成
    session_id BIGINT NOT NULL, -- 所属面试会话 ID，关联 interview_session.id
    round_no INTEGER NOT NULL, -- 主问题轮次，从 1 开始；同一轮的追问沿用该轮次
    follow_up_no INTEGER NOT NULL DEFAULT 0, -- 轮内顺序，0 表示主问题，正整数表示第几道追问
    parent_question_id BIGINT, -- 追问所针对的本场题目 ID，主问题为空
    question TEXT NOT NULL, -- 本场实际使用的题干快照
    category VARCHAR(64), -- 本场题目的考察分类，可为空
    reference_answer TEXT, -- 出题时保存的参考答案，可为空
    key_points_json JSONB, -- 出题时保存的答题要点，格式为 JSON 数组，可为空
    scoring_rubric TEXT, -- 出题时保存的单题评分标准，可为空
    follow_up_candidates_json JSONB, -- 专项主问题的候选追问快照，以 JSON 数组保存，供现场生成追问时参考
    user_answer TEXT, -- 用户首次正式提交的答案，未作答时为空
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, -- 该题目加入本场面试的时间
    answered_at TIMESTAMPTZ, -- 用户正式提交答案的时间，未作答时为空

    CONSTRAINT pk_interview_session_question PRIMARY KEY (id),
    CONSTRAINT uk_interview_session_question_order UNIQUE (session_id, round_no, follow_up_no),
    CONSTRAINT uk_interview_session_question_session_id UNIQUE (session_id, id),
    CONSTRAINT fk_interview_session_question_session
        FOREIGN KEY (session_id) REFERENCES interview_session(id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_session_question_parent
        FOREIGN KEY (session_id, parent_question_id)
        REFERENCES interview_session_question(session_id, id),
    CONSTRAINT ck_interview_session_question_round_no CHECK (round_no > 0),
    CONSTRAINT ck_interview_session_question_follow_up_no CHECK (follow_up_no >= 0),
    CONSTRAINT ck_interview_session_question_parent CHECK (
        (follow_up_no = 0 AND parent_question_id IS NULL)
        OR (follow_up_no > 0 AND parent_question_id IS NOT NULL AND parent_question_id <> id)
    ),
    CONSTRAINT ck_interview_session_question_text_not_blank CHECK (BTRIM(question) <> ''),
    CONSTRAINT ck_interview_session_question_key_points
        CHECK (key_points_json IS NULL OR jsonb_typeof(key_points_json) = 'array'),
    CONSTRAINT ck_interview_session_question_follow_up_candidates CHECK (
        follow_up_candidates_json IS NULL
        OR (follow_up_no = 0 AND jsonb_typeof(follow_up_candidates_json) = 'array')
    ),
    CONSTRAINT ck_interview_session_question_answer CHECK (
        (answered_at IS NULL AND user_answer IS NULL)
        OR (answered_at IS NOT NULL AND answered_at >= created_at
            AND user_answer IS NOT NULL AND BTRIM(user_answer) <> '')
    )
);

-- 建好两张表后再添加当前题目的外键，并保证当前题属于该会话。
ALTER TABLE interview_session
    ADD CONSTRAINT fk_interview_session_current_question
        FOREIGN KEY (id, current_question_id)
        REFERENCES interview_session_question(session_id, id);

CREATE INDEX idx_interview_session_user_created
    ON interview_session (user_id, created_at DESC, id DESC);
CREATE INDEX idx_interview_session_resume ON interview_session (resume_id);
CREATE INDEX idx_interview_session_knowledge_base ON interview_session (knowledge_base_id);

